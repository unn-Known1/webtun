// WebTun frontend - terminal.js (terminal WS, xterm core, keys, search, mobile.)

function cleanupWebSocket(tab) {
  clearTimeout(tab._initialPromptTimer);
  tab._initialPromptTimer = null;
  if (tab._openTimer) {
    try { clearTimeout(tab._openTimer); } catch {}
    tab._openTimer = null;
  }
  if (tab.ws) {
    tab.ws.onopen = null;
    tab.ws.onmessage = null;
    tab.ws.onerror = null;
    tab.ws.onclose = null;
    try { tab.ws.close(); } catch(e) { console.warn(e); }
    tab.ws = null;
  }
  if (tab.pingTimer) {
    clearInterval(tab.pingTimer);
    tab.pingTimer = null;
  }
}

function terminalRetryPolicy(tab) {
  return tab.retryPolicy || (tab.retryPolicy = WebTunTerminalConnection.createRetryPolicy());
}

function stopInitialPromptRedraw(tab) {
  tab._initialPromptPending = false;
  clearTimeout(tab._initialPromptTimer);
  tab._initialPromptTimer = null;
}

function sendTerminalInput(tab, text) {
  // Device/cursor reports are generated by xterm, rather than by the user.
  // Exempt all of their shapes — OSC color replies (\x1b]10/11;...), DECRPM
  // (\x1b[?...$y), DA, CPR, and kitty-keyboard — or the startup prompt-redraw
  // gets cancelled before it can fix the blank-rows gap.
  if (!terminalGeneratedInput(text)) stopInitialPromptRedraw(tab);
  sendWsInput(tab.ws, text);
}

function terminalGeneratedInput(text) {
  return /^(?:\x1b\[[?>=]?[0-9;]*[cRnsuIOtT]|\x1b\[\?[0-9;]+\$y|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\))+$/.test(text);
}

function redrawInitialPrompt(tab, ws) {
  if (!tab._initialPromptPending) return;
  clearTimeout(tab._initialPromptTimer);
  // Let split startup frames finish before deciding whether the gap is empty.
  tab._initialPromptTimer = setTimeout(() => {
    tab._initialPromptTimer = null;
    if (!tab._initialPromptPending || tab.closed || tab.ws !== ws || ws.readyState !== WebSocket.OPEN) return;
    const buffer = tab.term.buffer.active;
    const line = buffer.getLine(buffer.baseY + buffer.cursorY);
    if (!line?.translateToString(true).trim()) return;
    if (!buffer.cursorY || buffer.baseY) {
      // Prompt already at the top, or scrolled back — nothing to repair.
      stopInitialPromptRedraw(tab);
      return;
    }
    if (buffer.type === 'normal' && xtermMouseTracking(tab.term)) {
      // A TUI drew itself on the normal screen — Ctrl+L must not wipe it.
      stopInitialPromptRedraw(tab);
      return;
    }
    for (let row = 0; row < buffer.cursorY; row++) {
      if (buffer.getLine(row)?.translateToString(true).trim()) {
        // Genuine output already above the prompt — not the blank-gap case.
        stopInitialPromptRedraw(tab);
        return;
      }
    }
    stopInitialPromptRedraw(tab);
    // Readline/PSReadLine redraw their prompt at the top on Ctrl+L. Asking the
    // shell to redraw keeps its cursor model synchronized with xterm.
    sendWsInput(ws, '\x0c');
  }, 100);
}

function connectWebSocket(tab, isReconnect = false) {
  if (tab.closed || !tab.term) return;
  if (isReconnect) stopInitialPromptRedraw(tab);
  clearTimeout(tab.reconnectTimer);
  cleanupWebSocket(tab);

  const proto = location.protocol === 'https:' ? 'wss' : 'ws';
  const cols = tab.term.cols, rows = tab.term.rows;
  const sessionParam = tab.sessionId ? `&session=${encodeURIComponent(tab.sessionId)}` : '';
  const wsUrl = `${proto}://${location.host}/ws?token=${encodeURIComponent(authToken)}&cols=${cols}&rows=${rows}&cwd=${encodeURIComponent(tab.cwd || currentPath)}${sessionParam}`;
  const ws = new WebSocket(wsUrl);
  tab.ws = ws;
  ws.binaryType = 'arraybuffer';
  // Open timeout: a WS upgrade hung inside the tunnel (cloudflared edge /
  // proxy buffering the handshake) stays in CONNECTING forever — no onopen,
  // no onclose, no banner, just a stuck "Connecting…" overlay. Force-close
  // so the onclose retry path below takes over.
  try { if (tab._openTimer) clearTimeout(tab._openTimer); } catch {}
  tab._openTimer = setTimeout(() => {
    try {
      if (tab.ws === ws && ws.readyState === WebSocket.CONNECTING) {
        try { ws.close(); } catch {}
        // If the browser never fires onclose for the aborted handshake,
        // drive the retry path directly (guarded: onclose clears _openTimer).
        setTimeout(() => {
          try {
            if (tab.ws === ws && ws.readyState !== WebSocket.OPEN && typeof ws.onclose === 'function') {
              ws.onclose();
            }
          } catch {}
        }, 1000);
      }
    } catch {}
  }, 10000);

  const sendInput = data => {
    if (ws.readyState !== WebSocket.OPEN) {
      // Never drop typing silently: keep the history buffer in sync and nudge
      // the user (throttled) instead of losing keystrokes.
      try {
        const now = Date.now();
        if (!tab._discToastAt || now - tab._discToastAt > 5000) {
          tab._discToastAt = now;
          toast('Terminal reconnecting — input not sent', 'warning');
        }
      } catch {}
      trackTermKeystrokes(tab, data);
      return;
    }
    // Modifier latches for mobile keyboard (Termius-grade touch interaction)
    if (typeof ctrlLatch !== 'undefined' && ctrlLatch && typeof data === 'string' && data.length === 1) {
      const code = data.toLowerCase().charCodeAt(0);
      if (code >= 97 && code <= 122) { // a-z -> 0x01..0x1a
        data = String.fromCharCode(code - 96);
      } else if (data === '[') {
        data = '\x1b';
      } else if (data === '\\') {
        data = '\x1c';
      }
      ctrlLatch = false;
      if (typeof updateModifierButtons === 'function') updateModifierButtons();
    } else if (typeof altLatch !== 'undefined' && altLatch && typeof data === 'string' && data.length === 1 && data.charCodeAt(0) >= 0x20) {
      data = '\x1b' + data;
      altLatch = false;
      if (typeof updateModifierButtons === 'function') updateModifierButtons();
    } else if (typeof shiftLatch !== 'undefined' && shiftLatch && typeof data === 'string' && data.length === 1 && data >= 'a' && data <= 'z') {
      data = data.toUpperCase();
      shiftLatch = false;
      if (typeof updateModifierButtons === 'function') updateModifierButtons();
    }

    // On Enter, capture the command for history
    for (let i = 0; i < data.length; i++) {
      const ch = data.charCodeAt(i);
      if (ch === 13 || ch === 10) { // Enter
        try {
          // Prefer stored paste text
          let text = tab._lastPasteText;
          tab._lastPasteText = null;
          if (text) {
            // For multi-line pastes, take only the last line (the command)
            const lines = text.split('\n');
            text = lines[lines.length - 1] || lines[lines.length - 2] || text;
            text = text.trim();
          } else {
            // Use the tracked input buffer (more reliable than buffer scanning)
            text = (tab._currentInput || '').trim();
            // Strip leaked device-attribute replies (e.g. ">0;276;0c") that
            // bypassed the escape parser — narrowed to that shape so digit-
            // leading commands like "2to3" are never eaten. Repeated, because a
            // session start produces a burst of them back to back (DA, DA2 and
            // the OSC 10/11 colour replies) and only the first one can match a
            // single-strip regex.
            for (let guard = 0; guard < 8; guard++) {
              const stripped = text
                .replace(/^[>?][0-9;]*c(?=[a-zA-Z/\\~\-.]|$)/, '')
                .replace(/^[0-9]{1,3};(?:[0-9]{1,3};)?rgb:[0-9a-fA-F/]{3,}/, '')
                .trim();
              if (stripped === text) break;
              text = stripped;
            }
          }
          if (text) addToCmdHist(text);
          tab._currentInput = ''; // Clear after history save
        } catch {}
      }
    }
    // Chunked send (server caps input per message)
    sendTerminalInput(tab, data);

    trackTermKeystrokes(tab, data);
  };
  // Keystroke model for command-history capture. Tracks printable input plus
  // common readline edits so the saved history matches the real line:
  // Backspace/DEL, ^U (kill line), ^W (kill word), ^C/^D (abandon line),
  // ^K (kill to end → yank buffer), ^Y (yank back), ^A/^E (cursor jumps —
  // buffer unchanged), Alt-F/B (word jumps — unchanged), Alt-D (kill word
  // forward — approximated as trailing-word kill). Arrow-key cursor edits
  // inside the line can't be modeled without cursor state, so mid-line
  // edits may still diverge; the buffer is capped to the tail.
  function trackTermKeystrokes(tab, data) {
    // Update the keystroke buffer — skip all escape sequences and control characters
    for (let i = 0; i < data.length; i++) {
      const ch = data.charCodeAt(i);
      if (ch === 13 || ch === 10) { // Enter (handled above)
        continue;
      } else if (ch === 127 || ch === 8) { // Backspace / Delete
        if (tab._currentInput) tab._currentInput = tab._currentInput.slice(0, -1);
      } else if (ch === 21) { // ^U — clear line
        tab._currentInput = '';
      } else if (ch === 3 || ch === 4) { // ^C / ^D — line killed, abandon buffer
        tab._currentInput = '';
        tab._lastPasteText = null;
      } else if (ch === 23) { // ^W — delete word
        if (tab._currentInput) tab._currentInput = tab._currentInput.replace(/\S+\s*$/, '');
      } else if (ch === 11) { // ^K — kill to end of line
        tab._yank = tab._currentInput || '';
        tab._currentInput = '';
      } else if (ch === 25) { // ^Y — yank back
        if (tab._yank) tab._currentInput = (tab._currentInput || '') + tab._yank;
      } else if (ch === 1 || ch === 5) { // ^A / ^E — cursor jump only
      } else if (ch === 27) { // ESC — escape sequence, or an Alt-modified key
        // Order matters: the introducers below are checked BEFORE the Meta
        // branch. ESC + a printable-looking byte is usually a sequence, not
        // Alt: arrow keys (ESC [ A), SS3 (ESC O A) and the device-attribute /
        // colour replies xterm.js answers on the PTY's behalf (ESC [ ? 1;2 c,
        // ESC ] 11;rgb:… ESC \) all start with ESC + a byte in 0x5B/0x4F/0x5D.
        // The Meta check used to win, consumed the introducer as "Alt+[" and
        // appended the sequence *body* as typed text — so a single arrow key,
        // or the reply burst every session start produces, was prepended to
        // the next command saved in history.
        const next = data.charCodeAt(i + 1);
        const after = data.charCodeAt(i + 2);
        const isParamOrIntermediate = c => c >= 0x20 && c <= 0x3f; // CSI params/mid
        const isFinalByte = c => c >= 0x40 && c <= 0x7e;
        const isSsh3Final = c => 'ABCDHFMPQRS'.indexOf(String.fromCharCode(c)) >= 0;
        // CSI: '[' + param/intermediate. An '[' at the very end of a chunk is
        // treated as CSI too — the rest arrives in the next chunk and is
        // dropped as a body, which is safer than recording it as typed text.
        if (next === 0x5b && (after === undefined || isParamOrIntermediate(after))) {
          i += 2;
          while (i < data.length && !isFinalByte(data.charCodeAt(i))) i++;
          continue;
        }
        // SS3: 'O' + a cursor/function final (Alt-O is readline open-line).
        if (next === 0x4f && after !== undefined && isSsh3Final(after)) { i += 2; continue; }
        // OSC / DCS / SOS / PM / APC — ']', 'P', 'X', '^', '_'
        if (next === 0x5d || next === 0x50 || next === 0x58 || next === 0x5e || next === 0x5f) {
          i++;
          if (data[i] === ']') { // OSC — skip to BEL or ESC-backslash (title text isn't input)
            i++;
            while (i < data.length) {
              if (data.charCodeAt(i) === 7) { i++; break; }
              if (data[i] === '\x1b' && data[i+1] === '\\') { i += 2; break; }
              i++;
            }
            i--; // compensate for-loop increment (already past terminator)
          } else { // DCS and friends — skip to ESC-backslash
            i++;
            while (i < data.length) {
              if (data[i] === '\x1b' && data[i+1] === '\\') { i += 2; break; }
              i++;
            }
            i--;
          }
          continue;
        }
        // Alt-letter (Meta): ESC followed by a printable is a readline word
        // command, not a terminal sequence. Alt-F/B jump (no buffer change);
        // Alt-D kills the word forward (approximate as trailing-word kill).
        if (next >= 32 && next < 127) {
          const meta = data[i + 1].toLowerCase();
          if (meta === 'd') {
            if (tab._currentInput) tab._currentInput = tab._currentInput.replace(/\S+\s*$/, '');
          }
          i++; // consume the Alt-modified char
          continue;
        }
        i++;
        if (data[i] === ']') { // OSC — skip to BEL or ESC-backslash (title text isn't input)
          i++;
          while (i < data.length) {
            if (data.charCodeAt(i) === 7) { i++; break; }
            if (data[i] === '\x1b' && data[i+1] === '\\') { i += 2; break; }
            i++;
          }
          i--; // compensate for-loop increment (already past terminator)
        } else if (data[i] === 'P') { // DCS — skip to ESC-backslash
          i++;
          while (i < data.length) {
            if (data[i] === '\x1b' && data[i+1] === '\\') { i += 2; break; }
            i++;
          }
          i--;
        } else { // CSI / SS3 / single-ESC — skip to final char (for-loop moves past it)
          while (i < data.length) {
            const c = data.charCodeAt(i);
            if (c >= 0x40 && c <= 0x7E) break;
            i++;
          }
        }
      } else if (ch >= 32 && ch !== 127) { // Printable (incl. unicode), not DEL
        tab._currentInput = (tab._currentInput || '') + data[i];
        // Cap buffer on long-lived tabs (history only needs the tail)
        if (tab._currentInput.length > 4096) tab._currentInput = tab._currentInput.slice(-4096);
      }
      // All other control chars (0x00-0x1F except 0x0D/0x0A) are silently dropped
    }
  };
  const sendResize = (cols, rows) => {
    if (ws.readyState !== WebSocket.OPEN) return;
    const dv = new DataView(new ArrayBuffer(5));
    dv.setUint8(0, 0x01); dv.setUint16(1, cols, true); dv.setUint16(3, rows, true);
    ws.send(dv.buffer);
  };

  ws.onopen = () => {
    try { if (tab._openTimer) { clearTimeout(tab._openTimer); tab._openTimer = null; } } catch {}
    terminalRetryPolicy(tab).reset();
    hideTermLoading(tab);
    try { if (typeof clearTabExited === 'function') clearTabExited(tab); } catch {}
    try { if (typeof refreshConnStatus === 'function') refreshConnStatus(); else updateConnStatus(true); } catch {}
    const banner = document.getElementById('reconnect-banner');
    if (banner) {
      banner.innerHTML = '<span class="reconnect-spinner"><svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="23 4 23 10 17 10"/><path d="M20.49 15a9 9 0 1 1-2.12-9.36L23 10"/></svg></span> Reconnecting…';
      banner.style.display = 'none';
    }
    if (isReconnect) {
      tab.term.writeln('\x1b[32m[Reconnected]\x1b[0m');
    }
    tab.pingTimer = setInterval(() => {
      if (ws.readyState === WebSocket.OPEN) ws.send(new Uint8Array([0x02]).buffer);
    }, 20000);
  };

  // OSC sequence handler: intercepts OSC 7, 133, 52 for app state, and
  // forwards OSC 0/1/2 (window/icon titles) to xterm so onTitleChange fires.
  // Frames are UTF-8 decoded with a streaming decoder (a multibyte char split
  // across two 0x00 frames no longer decodes as U+FFFD), and a trailing
  // unterminated OSC is held in oscBuf and prepended to the next frame.
  let oscBuf = '';
  if (!tab._termDecoder) { try { tab._termDecoder = new TextDecoder(); } catch {} }
  function handleOsc52(value, tab) {
    const parts = value.split(';');
    const targets = parts[0];
    const isCopyTarget = !targets || targets.includes('c') || targets.includes('p') || targets.includes('s');
    const b64 = parts.slice(1).join(';');
    if (b64) {
      // SET clipboard — always honored (a program can only overwrite,
      // never read). UTF-8 safe, so emoji/CJK are no longer dropped.
      try {
        const decoded = b64ToUtf8(b64);
        if (isCopyTarget) {
          navigator.clipboard.writeText(decoded).then(() => {
            const now = Date.now();
            if (!tab._lastOsc52Toast || now - tab._lastOsc52Toast > 1500) {
              tab._lastOsc52Toast = now;
              try { toast('Copied to clipboard', 'success', { log: false }); } catch {}
            }
          }).catch(() => {
            try {
              const ta = document.createElement('textarea');
              ta.value = decoded;
              ta.style.position = 'fixed';
              ta.style.opacity = '0';
              document.body.appendChild(ta);
              ta.select();
              document.execCommand('copy');
              document.body.removeChild(ta);
              const now = Date.now();
              if (!tab._lastOsc52Toast || now - tab._lastOsc52Toast > 1500) {
                tab._lastOsc52Toast = now;
                try { toast('Copied to clipboard', 'success', { log: false }); } catch {}
              }
            } catch (_) {}
          });
        }
      } catch (_) {}
    } else if (settings.clipboardRead) {
      // GET clipboard — opt-in (Settings → Terminal). Any remote
      // output could otherwise pull the local clipboard into the
      // session with no prompt at all.
      navigator.clipboard.readText().then(text => {
        const response = '\x1b]52;c;' + utf8ToB64(text) + '\x07';
        if (tab.ws && tab.ws.readyState === WebSocket.OPEN) {
          const enc = new TextEncoder().encode(response);
          const buf = new Uint8Array(1 + enc.length);
          buf[0] = 0x00; buf.set(enc, 1);
          tab.ws.send(buf.buffer);
        }
      }).catch(() => {});
    } else if (!tab._clipReadHintShown) {
      tab._clipReadHintShown = true;
      toast('A program asked to read your clipboard — enable "Allow terminal clipboard read" in Settings', 'warning');
    }
  }

  function processTerminalOutput(data) {
    let chunk;
    if (typeof data === 'string') chunk = data;
    else { try { chunk = tab._termDecoder.decode(data, { stream: true }); } catch { chunk = new TextDecoder().decode(data); } }
    const str = oscBuf + chunk;
    oscBuf = '';
    let out = '';
    let i = 0;
    while (i < str.length) {
      // If trailing char is bare ESC, buffer it for next chunk to avoid splitting introducer
      if (i === str.length - 1 && str[i] === '\x1b') {
        oscBuf = '\x1b';
        break;
      }

      // Check for tmux DCS wrapped sequence: \x1bPtmux;\x1b...
      if (str.startsWith('\x1bPtmux;\x1b', i) || str.startsWith('\x1bPtmux;', i)) {
        const pfxLen = str.startsWith('\x1bPtmux;\x1b', i) ? 8 : 7;
        const dcsEnd = str.indexOf('\x1b\\', i + pfxLen);
        if (dcsEnd !== -1) {
          const inner = str.substring(i + pfxLen, dcsEnd).replace(/\x1b\x1b/g, '\x1b');
          if (inner.startsWith('\x1b]52;') || inner.startsWith(']52;')) {
            handleOsc52(inner.startsWith('\x1b]') ? inner.substring(4) : inner.substring(3), tab);
            i = dcsEnd + 2;
            continue;
          }
        } else {
          oscBuf = str.substring(i);
          if (oscBuf.length > 1048576) { out += oscBuf; oscBuf = ''; }
          break;
        }
      }

      // Look for ESC ] (OSC introducer)
      if (str[i] === '\x1b' && str[i + 1] === ']') {
        const endIdx = str.indexOf('\x07', i + 2);
        const stIdx = str.indexOf('\x1b\\', i + 2);
        let oscEnd = -1;
        if (endIdx !== -1 && (stIdx === -1 || endIdx < stIdx)) oscEnd = endIdx;
        else if (stIdx !== -1) oscEnd = stIdx;

        if (oscEnd !== -1) {
          const oscData = str.substring(i + 2, oscEnd);
          const semi = oscData.indexOf(';');
          if (semi !== -1) {
            const code = oscData.substring(0, semi);
            const value = oscData.substring(semi + 1);
            if (code === '7') {
              // OSC 7: CWD update — file://hostname/path
              try {
                const url = new URL(value);
                tab.cwd = decodeURIComponent(url.pathname);
              } catch (_) {}
            } else if (code === '133') {
              // OSC 133: Shell integration markers (prompt/cmd start/end/done)
              // Handled silently — available for future command tracking
            } else if (code === '52') {
              // OSC 52: Clipboard operations
              handleOsc52(value, tab);
            } else {
              // OSC 0/1/2 (window/icon titles) and anything else we do not
              // consume: forward verbatim so xterm fires onTitleChange.
              out += str.substring(i, oscEnd + (str[oscEnd] === '\x07' ? 1 : 2));
            }
          }
          i = oscEnd + (str[oscEnd] === '\x07' ? 1 : 2);
          continue;
        } else {
          // Unterminated OSC at the end of this frame: hold it for the next
          // frame instead of leaking escape garbage into the terminal.
          oscBuf = str.substring(i);
          if (oscBuf.length > 1048576) { out += oscBuf; oscBuf = ''; }
          break;
        }
      }
      out += str[i];
      i++;
    }
    if (out) {
      clearTimeout(tab._initialPromptTimer);
      tab.term.write(out, () => redrawInitialPrompt(tab, ws));
      try { scanPreviewHint(tab, out.slice(-2000)); } catch {}
      try { if (typeof notifyTabOutput === 'function') notifyTabOutput(tab); } catch {}
    }
  }

  // Defensive: ws.binaryType is set to 'arraybuffer' right after construction,
  // but a Blob frame (or an unexpected string frame) must not throw inside the
  // message handler — that would kill the socket handler mid-session.
  ws.onmessage = async e => {
    let buf;
    if (e.data instanceof ArrayBuffer) {
      buf = new Uint8Array(e.data);
    } else if (typeof Blob !== 'undefined' && e.data instanceof Blob) {
      try { buf = new Uint8Array(await e.data.arrayBuffer()); } catch { return; }
    } else if (typeof e.data === 'string') {
      buf = new TextEncoder().encode(e.data);
    } else {
      return;
    }
    if (!buf.length) return;
    const type = buf[0], payload = buf.slice(1);
    if (type === 0x00) processTerminalOutput(payload);
    else if (type === 0x01) { tab.term.writeln('\r\n\x1b[31m[Process exited]\x1b[0m'); try { if (typeof notifyTabExited === 'function') notifyTabExited(tab); } catch {} }
    else if (type === 0x02) tab.term.writeln('\r\n\x1b[31m' + new TextDecoder().decode(payload) + '\x1b[0m');
    else if (type === 0x03) handleClientEvent(payload);
  };

// Server-pushed security events (0x03 JSON): new-login alerts, session-revoked kicks.
function handleClientEvent(payload) {
  let ev = null;
  try { ev = JSON.parse(new TextDecoder().decode(payload)); } catch { return; }
  if (!ev || !ev.event) return;
  if (ev.event === 'new-login') {
    const when = ev.at ? new Date(ev.at).toLocaleString() : 'just now';
    toast(`New login — ${ev.device || 'unknown device'} · ${ev.ip || 'unknown IP'} · ${when}`, 'warning');
    // Persistent triangle until reviewed (toast alone vanishes)
    try { addSecurityAlert(ev); } catch {}
    try { updateSessionCupCount(); } catch {}
    // Refresh the sessions list if the Security panel is visible
    try {
      const sp = document.getElementById('settings-panel');
      if (sp && sp.classList.contains('open') && typeof refreshSessions === 'function') refreshSessions();
    } catch {}
  } else if (ev.event === 'session-revoked') {
    toast('This session was signed out remotely', 'error');
    storeSessionToken('');
    authToken = '';
    // Stop the reconnect loop or tabs keep dialling with a dead token
    // behind the lock screen.
    try {
      (tabs || []).forEach(t => {
        try { clearTimeout(t.reconnectTimer); } catch {}
        try { cleanupWebSocket(t); } catch {}
      });
    } catch {}
    showPinScreen();
  } else if (ev.event === 'session-pending') {
    // A new device passed the PIN but is locked until WE approve it.
    // Instant modal here; the sessions list holds Approve/Deny as backstop.
    try { if (typeof refreshSessions === 'function') refreshSessions(); } catch {}
    try { updateSessionCupCount(); } catch {}
    try { addSecurityAlert({ ip: ev.ip, device: `Login approval requested by ${ev.device || 'unknown device'}`, at: ev.at }); } catch {}
    confirmDialog({
      title: 'Approve this device?',
      message: `${ev.device || 'Unknown device'} (${ev.ip || 'unknown IP'}) entered the correct PIN and is waiting for access. Approve it, or dismiss and Deny it in Security.`,
      okText: 'Approve device', cancelText: 'Dismiss', danger: true,
    }).then(async ok => {
      if (!ok) return;
      await approveSession(ev.id);
    }).catch(() => {});
  } else if (ev.event === 'pin-change-pending') {
    // A fresh session asked to rotate the PIN. Act in this very moment:
    // instant modal here, persistent banner in Security as backstop.
    try { if (typeof refreshSessions === 'function') refreshSessions(); } catch {}
    const mine = ev.requester && ev.requester === authToken;
    if (mine) {
      toast('PIN change pending — approve it from another signed-in tab', 'info');
    } else {
      const when = ev.expiresAt ? new Date(ev.expiresAt).toLocaleTimeString() : '';
      confirmDialog({
        title: 'Approve PIN change?',
        message: `${ev.device || 'Unknown device'} (${ev.ip || 'unknown IP'}) wants to change the PIN${when ? ` — expires ${when}` : ''}. If this wasn't you, dismiss and Revert it in Security.`,
        okText: 'Approve change', cancelText: 'Dismiss', danger: true,
      }).then(async ok => {
        if (!ok) return;
        await approvePinChange();
      }).catch(() => {});
      try { addSecurityAlert({ ip: ev.ip, device: `PIN change requested by ${ev.device || 'unknown device'}`, at: Date.now() }); } catch {}
    }
  } else if (ev.event === 'pin-change-resolved') {
    toast(ev.approved ? 'PIN change approved and applied' : `PIN change stopped${ev.expired ? ' (expired)' : ''}${ev.vetoed ? ' (reverted)' : ''}`, ev.approved ? 'success' : 'info');
    try { if (typeof refreshSessions === 'function') refreshSessions(); } catch {}
    try { updateSessionCupCount(); } catch {}
  } else if (ev.event === 'pin-changed') {
    const what = ev.disabled ? 'PIN protection was REMOVED' : 'PIN was changed';
    toast(`${what} by ${ev.device || 'unknown device'} · ${ev.ip || 'unknown IP'} — re-login required`, 'error');
    // Persistent: survives the kick to the PIN screen, shown on next unlock
    try { addSecurityAlert({ ip: ev.ip, device: `${what} by ${ev.device || 'unknown device'}`, at: ev.at }); } catch {}
    // The rotation revoked this token server-side: drop it now and stop the
    // sockets instead of limping on until the next 401/close.
    storeSessionToken('');
    authToken = '';
    try {
      (tabs || []).forEach(t => {
        try { clearTimeout(t.reconnectTimer); } catch {}
        try { cleanupWebSocket(t); } catch {}
      });
    } catch {}
    try { showPinScreen(); } catch {}
  } else if (ev.event === 'sessions-changed') {
    try { updateSessionCupCount(); } catch {}
    try {
      const sp = document.getElementById('settings-panel');
      if (sp && sp.classList.contains('open') && typeof refreshSessions === 'function') refreshSessions();
    } catch {}
    try {
      const modal = document.getElementById('term-sessions-overlay');
      if (modal && modal.classList.contains('open') && typeof refreshTerminalSessionsModal === 'function') refreshTerminalSessionsModal(true);
    } catch {}
    try {
      if (typeof updateLaunchpad === 'function') updateLaunchpad();
    } catch {}
  }
}

  ws.onerror = () => {
    try { console.warn('WS error on tab', tab.id); } catch {}
    // A failed handshake through the tunnel often errors without ever
    // opening — make sure it doesn't linger in CONNECTING.
    try { if (ws.readyState === WebSocket.CONNECTING) ws.close(); } catch {}
  };

  ws.onclose = event => {
    try { if (tab._openTimer) { clearTimeout(tab._openTimer); tab._openTimer = null; } } catch {}
    // The open-timeout's fallback may invoke onclose after cleanup already
    // ran for a newer socket — never kill a live replacement.
    if (tab.ws && tab.ws !== ws) return;
    cleanupWebSocket(tab);
    const policy = terminalRetryPolicy(tab);
    const retry = policy.next({ closed: tab.closed, code: event?.code, reason: event?.reason, sessionId: tab.sessionId });
    if (tab.closed) return;
    if (retry.action === 'auth') {
      hideTermLoading(tab);
      try { showPinScreen(); } catch {}
      return;
    }
    try { if (typeof refreshConnStatus === 'function') refreshConnStatus(); else updateConnStatus(false); } catch {}
    const _attempt = retry.attempt;
    const _maxAttempts = policy.maxAttempts;
    const spinnerHtml = '<span class="reconnect-spinner"><svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="23 4 23 10 17 10"/><path d="M20.49 15a9 9 0 1 1-2.12-9.36L23 10"/></svg></span>';
    const banner = document.getElementById('reconnect-banner');
    // Honor the cap: after _maxAttempts, stop auto-retry and leave the
    // manual Reconnect button (auto-loop never yielded before).
    if (retry.action === 'fresh') {
      tab.sessionId = uuid();
      tab.term.writeln('\r\n\x1b[33m[Session expired — starting a fresh session…]\x1b[0m');
      tab.reconnectTimer = setTimeout(() => { tab.reconnectTimer = null; if (!tab.closed) connectWebSocket(tab, true); }, retry.delay);
      return;
    }
    if (retry.action === 'stop') {
      if (retry.reason) toast('Terminal connection stopped: ' + retry.reason, 'warning');
      if (banner) {
        banner.innerHTML = `Connection lost — auto-retry stopped. <button class="btn btn-primary btn-reconnect" data-action="reconnect-terminal">Reconnect</button>`;
        banner.style.display = 'block';
      }
      tab.term.writeln('\r\n\x1b[33m[Disconnected — auto-retry stopped. Press Reconnect above.]\x1b[0m');
      // The "Connecting…" overlay covers the whole terminal (z-index 3), so
      // without this the failure message underneath stays invisible forever.
      try { if (typeof hideTermLoading === 'function') hideTermLoading(tab); } catch {}
      try { if (typeof refreshConnStatus === 'function') refreshConnStatus(); } catch {}
      return;
    }
    if (banner) {
      if (_attempt >= 3) {
        banner.innerHTML = `Connection lost — retry ${_attempt}/${_maxAttempts}. <button class="btn btn-primary btn-reconnect" data-action="reconnect-terminal">Reconnect</button>`;
      } else {
        banner.innerHTML = `${spinnerHtml} Reconnecting (${_attempt}/${_maxAttempts})…`;
      }
      banner.style.display = 'block';
    }
    const delay = retry.delay;
    const secs = (delay / 1000).toFixed(1).replace(/\.0$/, '');
    tab.term.writeln(`\r\n\x1b[33m[Disconnected — reconnecting in ${secs}s (attempt ${_attempt}/${_maxAttempts})…]\x1b[0m`);
    tab.reconnectTimer = setTimeout(() => {
      tab.reconnectTimer = null;
      if (!tab.closed) connectWebSocket(tab, true);
    }, delay);
  };

  tab.dataDisposable?.dispose();
  tab.resizeDisposable?.dispose();
  tab.dataDisposable = tab.term.onData(data => sendInput(data));
  tab.resizeDisposable = tab.term.onResize(({ cols, rows }) => sendResize(cols, rows));
}

function manualReconnect() {
  const banner = document.getElementById('reconnect-banner');
  if (banner) {
    banner.innerHTML = '<span class="reconnect-spinner"><svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="23 4 23 10 17 10"/><path d="M20.49 15a9 9 0 1 1-2.12-9.36L23 10"/></svg></span> Reconnecting (1/10)…';
    banner.style.display = 'block';
  }
  tabs.forEach(tab => {
    if (tab.closed) return;
    if (!tab.ws || tab.ws.readyState !== WebSocket.OPEN) {
      terminalRetryPolicy(tab).reset();
      connectWebSocket(tab, true);
    }
  });
}
function initTerminal(tab) {
  if (typeof Terminal === 'undefined') {
    tab._termInitRetries = (tab._termInitRetries || 0) + 1;
    if (tab._termInitRetries < 60) {
      setTimeout(() => initTerminal(tab), 50);
      return;
    }
    console.error('Terminal library (xterm.js) is not available');
    return;
  }

  const cfg = {
    fontFamily: settings.font,
    fontSize: settings.fontSize,
    cursorStyle: settings.cursor,
    cursorBlink: settings.blink,
    scrollback: settings.scrollback,
    allowTransparency: false,
    theme: getXtermTheme(),
    windowsMode: serverPlatform === 'win32',
    convertEol: false,
    bellStyle: settings.bell ? 'sound' : 'none',
    smoothScrollDuration: 80,
    selectionTheme: getXtermSelectionTheme(),
    trimTrailingWhitespace: true,
    rightClickSelectsWord: true
  };

  const term = new Terminal(cfg);
  const fitAddon = (typeof FitAddon !== 'undefined' && FitAddon.FitAddon) ? new FitAddon.FitAddon() : null;
  const webLinksAddon = (typeof WebLinksAddon !== 'undefined' && WebLinksAddon.WebLinksAddon) ? new WebLinksAddon.WebLinksAddon() : null;

  if (fitAddon) term.loadAddon(fitAddon);
  if (webLinksAddon) term.loadAddon(webLinksAddon);

  try {
    if (typeof Unicode11Addon !== 'undefined' && Unicode11Addon.Unicode11Addon) {
      const unicodeAddon = new Unicode11Addon.Unicode11Addon();
      term.loadAddon(unicodeAddon);
      term.unicode.activeVersion = '11';
    }
  } catch (_) {}

  // GPU-accelerated renderer — falls back to canvas if WebGL unavailable.
  // Guard counts LIVE WebGL contexts (not just tabs), so init churn can never
  // exhaust the browser's ~16-context budget.
  const liveGL = (typeof tabs !== 'undefined' ? tabs : []).filter(t => t && t._webglAddon).length;
  if (liveGL < 4 && typeof WebglAddon !== 'undefined' && WebglAddon.WebglAddon) {
    try {
      const webglAddon = new WebglAddon.WebglAddon();
      webglAddon.onContextLoss(() => {
        // Context lost: dispose the GL addon and fall back to the canvas
        // renderer (leave its canvas alone — removing it blanks the term).
        try { webglAddon.dispose(); } catch {}
        tab._webglAddon = null;
        try { term.refresh(0, term.rows - 1); } catch {}
        try { toast('3D renderer lost its context — using canvas fallback', 'warning'); } catch {}
      });
      term.loadAddon(webglAddon);
      tab._webglAddon = webglAddon;
    } catch (_) {}
  }

  term.open(tab.wrapper);

  // Keep TUI wheel events in xterm so alternate-screen apps receive their
  // expected arrow keys or mouse reports. For shell scrollback, preserve
  // fractional pixel deltas here so a trackpad does not jump a line per event.
  let _wheelScrollRemainder = 0;
  term.attachCustomWheelEventHandler(event => {
    if (event.ctrlKey || event.metaKey || event.shiftKey) return true;
    const atTop = term.buffer.active.baseY === 0;
    const atBottom = term.buffer.active.baseY + term.rows >= term.buffer.active.length;
    if (tilesMode && ((event.deltaY < 0 && atTop) || (event.deltaY > 0 && atBottom))) return false;
    // Keep xterm's native route for TUIs: it sends arrow keys in alternate
    // screen mode and mouse reports when the application enables mouse input.
    if (term.buffer.active.type !== 'normal' || xtermMouseTracking(term) || term.buffer.active.length <= term.rows) return true;

    let lines = event.deltaY;
    if (event.deltaMode === WheelEvent.DOM_DELTA_PIXEL) {
      _wheelScrollRemainder += event.deltaY / (xtermCharHeight(term, tab.wrapper) || 16);
      lines = Math.trunc(_wheelScrollRemainder);
      _wheelScrollRemainder -= lines;
    } else if (event.deltaMode === WheelEvent.DOM_DELTA_PAGE) {
      lines *= term.rows;
    }
    if (lines) term.scrollLines(Math.trunc(lines));
    // Consume the event even for a fractional pixel delta; the remainder is
    // retained until it adds up to one line.
    return false;
  });

  term.attachCustomKeyEventHandler(e => {
    if (e.type === 'keydown') {
      const isCmd = e.ctrlKey || e.metaKey;
      const key = e.key ? e.key.toLowerCase() : '';
      // Ctrl+Shift+C: standard terminal copy
      if (isCmd && e.shiftKey && key === 'c') {
        if (term.hasSelection()) {
          copyTermSelection();
          return false;
        }
      }
      // Ctrl+Shift+V: standard terminal paste
      if (isCmd && e.shiftKey && key === 'v') {
        pasteToTerminal();
        return false;
      }
      // Plain Ctrl+C / Cmd+C when text is selected: copy instead of sending SIGINT
      if (isCmd && !e.shiftKey && !e.altKey && key === 'c') {
        if (term.hasSelection()) {
          copyTermSelection();
          return false;
        }
      }
      // Quick search via Cmd+K / Ctrl+K vs Terminal TUI Ctrl+K passthrough:
      if (isCmd && key === 'k') {
        if (settings.passCtrlK) {
          if (e.shiftKey) {
            if (typeof openFinder === 'function') openFinder();
            return false;
          }
          // Plain Ctrl+K: return true so xterm passes it directly to TUI app!
          return true;
        }
        if (e.shiftKey) {
          // Ctrl+Shift+K sends literal Ctrl+K (\x0b) directly to the TUI app!
          sendKey('\x0b');
          return false;
        }
        if (typeof openFinder === 'function') openFinder();
        return false;
      }
      if (isCmd && e.shiftKey && key === 'p') {
        if (typeof openFinder === 'function') openFinder();
        return false;
      }
      // Ctrl+Shift+W closes the tab while inside terminal (protects plain Ctrl+W for vim/bash)
      if (isCmd && e.shiftKey && key === 'w') {
        if (activeTabId && typeof closeTab === 'function') closeTab(e, activeTabId);
        return false;
      }
      // Alt+1..9 for fast tab switching
      if (e.altKey && !e.ctrlKey && !e.metaKey && !e.shiftKey && /^[1-9]$/.test(e.key || '')) {
        return false;
      }
      // Note: plain Ctrl+B (tmux prefix), plain Ctrl+P (fzf/history), and plain Ctrl+W
      // return true to pass directly through to the terminal and running TUI process!
    }
    return true;
  });

  tab.term = term;
  tab.fitAddon = fitAddon;
  tab.closed = false;
  // Modes are global: a tab created mid-mode must match its siblings.
  try {
    if (typeof termSelectMode !== 'undefined' && termSelectMode) {
      term.options.disableStdin = true;
    }
    if (typeof scrollMode !== 'undefined' && scrollMode) {
      const h = (typeof attachScrollHandler === 'function') ? attachScrollHandler({ wrapper: tab.wrapper, term }) : null;
      if (h) _scrollHandlers.push(h);
    }
  } catch {}
  tab.textarea = term.textarea || term.element?.querySelector('.xterm-textarea, textarea');
  if (tab.textarea && !tab.textarea.id) {
    tab.textarea.id = 'xterm-helper-' + tab.id;
    tab.textarea.name = 'terminal-input';
  }

  // Intercept paste events to use bracketed paste mode (required for TUI apps like vim, nano, mc).
  // NOTE: xterm.js also listens for 'paste' on the same textarea and re-emits
  // it via onData. Without stopping propagation our bracketed send + xterm's
  // send fire together, pasting everything twice (notably with the native
  // browser context menu when the custom right-click menu is disabled).
  if (tab.textarea) {
    tab.textarea.addEventListener('paste', e => {
      e.preventDefault();
      e.stopImmediatePropagation();
      e.stopPropagation();
      const text = (e.clipboardData || window.clipboardData)?.getData('text');
      if (!text) return;
      tab._lastPasteText = text;
      tab._currentInput = ((tab._currentInput || '') + text.split('\n').pop()).slice(-4096);
      if (!tab.ws || tab.ws.readyState !== WebSocket.OPEN) {
        try { toast('Terminal reconnecting — paste not sent', 'warning'); } catch {}
        return;
      }
      // sendWsInput() chunks on character boundaries — the old fixed 60KB byte
      // slices cut multibyte characters in half, showing up as � in the shell.
      const bracketed = '\x1b[200~' + text + '\x1b[201~';
      try { sendTerminalInput(tab, bracketed); } catch {}
    }, true);
  }

  // term.onFocus() was removed from xterm.js — use native DOM event instead
  term.element.addEventListener('focusin', () => {
    if (activeTabId !== tab.id) {
      activateTab(tab.id);
    }
  });

  // Title updates from OSC
  term.onTitleChange(title => {
    tab.title = title || `Term ${tab.id}`;
    tab.el.querySelector('.tab-title').textContent = tab.title;
  });

  // Bell: visual flash + desktop notification for background tabs (also flash parent for WebGL)
  term.onBell(() => {
    try { if (typeof notifyTabBell === 'function') notifyTabBell(tab); } catch {}
    // Visual flash on terminal screen and parent (WebGL uses canvas, so also flash parent)
    const screen = term.element?.querySelector('.xterm-screen');
    const parent = term.element;
    [screen, parent].forEach(el => {
      if (!el) return;
      el.classList.remove('term-bell-flash');
      void el.offsetWidth; // reflow to restart animation
      el.classList.add('term-bell-flash');
      setTimeout(() => el.classList.remove('term-bell-flash'), 150);
    });
    // Desktop notification if tab is in the background
    if (document.hidden && settings.bell && Notification.permission === 'granted') {
      try {
        new Notification(tab.title || 'WebTun', { body: 'Terminal bell', tag: 'webtun-bell' });
      } catch (_) {}
    }
  });

  // Resize observer
  tab.resizeObserver = new ResizeObserver(() => {
    // In tile view every wrapper is visible, so background tiles must refit
    // too — they used to stay at their old size forever.
    if (tilesMode) {
      tabs.forEach(t => { if (t.term && t.wrapper) { try { fitTerm(t); } catch {} } });
      return;
    }
    if (activeTabId === tab.id) { try { fitTerm(tab); } catch(e) { console.warn(e); } }
  });
  tab.resizeObserver.observe(tab.wrapper);

  // Copy selection to clipboard using modern API
  term.element.addEventListener('copy', e => {
    const sel = term.getSelection();
    if (sel) {
      e.preventDefault();
      navigator.clipboard.writeText(sel).then(() => {
        toast('Copied to clipboard', 'success');
      }).catch(() => {
        document.execCommand('copy');
      });
    }
  });

  // Terminal right-click context menu
  term.element.addEventListener('contextmenu', e => {
    if (!settings.termRightClick) return;
    e.preventDefault();
    try { if (typeof hideAllCtxMenus === 'function') hideAllCtxMenus(); } catch {}
    // TR-02: bind the menu to the exact tile that was right-clicked, then
    // activate it so Tile View actions can't land on a background session.
    try { termCtxTabId = tab.id; } catch {}
    try { if (typeof activateTab === 'function' && activeTabId !== tab.id) activateTab(tab.id); } catch {}
    const menu = document.getElementById('term-ctx-menu');
    // TR-04: proper disabled state (not just dimmed opacity) for Copy.
    const copyItem = document.getElementById('term-ctx-copy');
    const sel = term.getSelection();
    const hasSel = !!sel;
    if (copyItem) {
      copyItem.classList.toggle('disabled', !hasSel);
      copyItem.setAttribute('aria-disabled', String(!hasSel));
      copyItem.style.opacity = '';
    }
    // Start closed: a submenu left open from the last invocation must not
    // affect this measurement or leak its expanded height into positioning.
    try {
      menu.querySelectorAll('.ctx-submenu-wrap.open').forEach(el => {
        el.classList.remove('open');
        el.querySelector(':scope > .ctx-item')?.setAttribute('aria-expanded', 'false');
      });
    } catch {}
    // Keyboard-invoked menus (Shift+F10 / Menu key) report 0,0 — anchor to
    // the terminal tile instead of the viewport origin.
    let cx = e.clientX, cy = e.clientY;
    if (cx === 0 && cy === 0) {
      try {
        const r = term.element.getBoundingClientRect();
        cx = r.left + Math.min(60, Math.max(20, r.width / 3));
        cy = r.top + Math.min(60, Math.max(20, r.height / 3));
      } catch { cx = 20; cy = 60; }
    }
    // Show first to measure actual dimensions
    menu.style.display = 'block';
    const mw = menu.offsetWidth;
    const mh = menu.offsetHeight;
    const vw = window.innerWidth;
    // TR-10: keep the menu above the mobile key bar + safe-area inset.
    const mobileKeys = document.getElementById('mobile-keys');
    const mobileOffset = (mobileKeys && mobileKeys.offsetHeight && window.innerWidth <= 768 &&
      getComputedStyle(mobileKeys).display !== 'none') ? mobileKeys.offsetHeight : 0;
    const vh = window.innerHeight - mobileOffset;
    let left = cx;
    let top = cy;
    // Flip horizontally if overflowing right
    if (left + mw > vw) left = Math.max(0, cx - mw);
    // Flip vertically if overflowing bottom (TR-01: clamped to usable vh)
    if (top + mh > vh) top = Math.max(0, cy - mh);
    // Clamp to viewport with an 8px margin
    left = Math.max(8, Math.min(left, vw - mw - 8));
    top = Math.max(8, Math.min(top, vh - mh - 8));
    // Guard against tiny viewports where mw/mh exceed the usable area.
    left = Math.max(8, left);
    top = Math.max(8, top);
    menu.style.left = left + 'px';
    menu.style.top = top + 'px';
    // TR-05: focus the menu container so arrow keys navigate items instead
    // of being sent to the shell. Focus returns to the terminal on dismiss
    // (see hideTermCtxMenu). The xterm cursor dims while the menu has focus
    // but no input is lost — the PTY keeps running underneath.
    try {
      menu.setAttribute('tabindex', '-1');
      menu.focus({ preventScroll: true });
    } catch { try { menu.focus(); } catch {} }
  });

  // Touch-to-mouse translation, smooth scrolling, and selection for mobile
  let _tapPos = null;
  let _lastTapTime = 0;
  let _lastTapPos = null;
  let _longPressTimer = null;
  let _isDraggingTouch = false;
  let _isSelectingDrag = false;
  let _selAnchor = null;
  let _touchAccumY = 0;
  let _lastTouchY = 0;
  let _lastTouchX = 0;
  let _pinchStartDist = 0;
  let _pinchStartFontSize = 14;
  let _pinchHudTimer = null;

  function showZoomHud(size) {
    const hud = document.getElementById('term-zoom-hud');
    if (!hud) return;
    hud.textContent = size + 'px';
    hud.style.display = 'block';
    hud.classList.add('visible');
    clearTimeout(_pinchHudTimer);
    _pinchHudTimer = setTimeout(() => {
      hud.classList.remove('visible');
      setTimeout(() => { hud.style.display = 'none'; }, 250);
    }, 1200);
  }

  term.element.addEventListener('touchstart', e => {
    if (e.touches.length === 1) e.stopImmediatePropagation();
    if (e.touches.length === 2) {
      clearTimeout(_longPressTimer);
      const dx = e.touches[0].clientX - e.touches[1].clientX;
      const dy = e.touches[0].clientY - e.touches[1].clientY;
      _pinchStartDist = Math.hypot(dx, dy);
      _pinchStartFontSize = term.options.fontSize || settings.fontSize || 14;
      return;
    }
    if (e.touches.length !== 1) {
      clearTimeout(_longPressTimer);
      return;
    }
    const touch = e.touches[0];
    _isDraggingTouch = false;
    _isSelectingDrag = false;
    _touchAccumY = 0;
    _lastTouchY = touch.clientY;
    _lastTouchX = touch.clientX;
    _tapPos = { x: touch.clientX, y: touch.clientY, time: Date.now() };

    // Check for double tap
    const now = Date.now();
    const dt = now - _lastTapTime;
    const isDoubleTap = _lastTapPos && dt < 320 && Math.hypot(touch.clientX - _lastTapPos.x, touch.clientY - _lastTapPos.y) < 25;

    if (isDoubleTap) {
      clearTimeout(_longPressTimer);
      _lastTapTime = 0;
      _lastTapPos = null;
      const cellInfo = getTermCellFromTouch(tab, touch.clientX, touch.clientY);
      if (cellInfo && selectWordAtCell(tab, cellInfo)) {
        showTermSelectionBar(touch.clientX, touch.clientY);
        try { navigator.vibrate?.(20); } catch {}
      }
      return;
    }
    _lastTapTime = now;
    _lastTapPos = { x: touch.clientX, y: touch.clientY };

    // Long press for text selection
    _longPressTimer = setTimeout(() => {
      if (_tapPos && !_isDraggingTouch) {
        const cellInfo = getTermCellFromTouch(tab, _tapPos.x, _tapPos.y);
        if (cellInfo) {
          _isSelectingDrag = true;
          _selAnchor = { col: cellInfo.col, bufRow: cellInfo.bufRow };
          selectWordAtCell(tab, cellInfo);
          showTermSelectionBar(_tapPos.x, _tapPos.y);
          try { navigator.vibrate?.(25); } catch {}
        }
      }
    }, 380);
  }, { passive: true, capture: true });

  term.element.addEventListener('touchmove', e => {
    if (e.touches.length === 2 && _pinchStartDist > 10) {
      e.preventDefault();
      e.stopImmediatePropagation();
      const dx = e.touches[0].clientX - e.touches[1].clientX;
      const dy = e.touches[0].clientY - e.touches[1].clientY;
      const dist = Math.hypot(dx, dy);
      const scale = dist / _pinchStartDist;
      const newSize = Math.max(9, Math.min(24, Math.round(_pinchStartFontSize * scale)));
      if (newSize !== term.options.fontSize) {
        term.options.fontSize = newSize;
        showZoomHud(newSize);
        fitTerm(tab);
      }
      return;
    }
    if (e.touches.length !== 1) return;
    // xterm's built-in touch scrolling would otherwise run alongside our
    // synthesized wheel event, making one swipe scroll the buffer twice.
    e.stopImmediatePropagation();
    const touch = e.touches[0];
    const totalDx = Math.abs(touch.clientX - (_tapPos ? _tapPos.x : touch.clientX));
    const totalDy = Math.abs(touch.clientY - (_tapPos ? _tapPos.y : touch.clientY));

    if (totalDx > 8 || totalDy > 8) {
      if (!_isSelectingDrag) clearTimeout(_longPressTimer);
    }

    if (_isSelectingDrag && _selAnchor) {
      e.preventDefault();
      const cellInfo = getTermCellFromTouch(tab, touch.clientX, touch.clientY);
      if (cellInfo) {
        const startRow = Math.min(_selAnchor.bufRow, cellInfo.bufRow);
        const endRow = Math.max(_selAnchor.bufRow, cellInfo.bufRow);
        if (startRow === endRow) {
          const startCol = Math.min(_selAnchor.col, cellInfo.col);
          const endCol = Math.max(_selAnchor.col, cellInfo.col);
          term.select(startCol, startRow, Math.max(1, endCol - startCol + 1));
        } else {
          term.selectLines(startRow, endRow);
        }
        showTermSelectionBar(touch.clientX, touch.clientY);
      }
      return;
    }

    if (termSelectMode) {
      e.preventDefault();
      const cellInfo = getTermCellFromTouch(tab, touch.clientX, touch.clientY);
      if (cellInfo) {
        if (!_selAnchor) _selAnchor = { col: cellInfo.col, bufRow: cellInfo.bufRow };
        const startRow = Math.min(_selAnchor.bufRow, cellInfo.bufRow);
        const endRow = Math.max(_selAnchor.bufRow, cellInfo.bufRow);
        if (startRow === endRow) {
          const startCol = Math.min(_selAnchor.col, cellInfo.col);
          const endCol = Math.max(_selAnchor.col, cellInfo.col);
          term.select(startCol, startRow, Math.max(1, endCol - startCol + 1));
        } else {
          term.selectLines(startRow, endRow);
        }
        showTermSelectionBar(touch.clientX, touch.clientY);
      }
      return;
    }

    // Touch scroll handling (vertical dominant)
    const dy = _lastTouchY - touch.clientY;
    const dx = _lastTouchX - touch.clientX;
    _lastTouchY = touch.clientY;
    _lastTouchX = touch.clientX;
    if (totalDy > totalDx * 0.7) _touchAccumY += dy;

    if (totalDy > 6 && totalDy > totalDx * 0.7) {
      _isDraggingTouch = true;
      // A swipe is not the first tap of a double-tap selection gesture.
      _lastTapTime = 0;
      _lastTapPos = null;
      e.preventDefault();

      const usesTuiWheel = term.buffer.active.type !== 'normal' || xtermMouseTracking(term);
      if (usesTuiWheel) {
        const vp = tab.wrapper.querySelector('.xterm-viewport');
        if (vp) vp.dispatchEvent(new WheelEvent('wheel', {
          deltaY: dy,
          deltaMode: WheelEvent.DOM_DELTA_PIXEL,
          clientX: touch.clientX,
          clientY: touch.clientY,
          bubbles: true,
          cancelable: true
        }));
        _touchAccumY = 0;
      } else {
        const lineHeight = xtermCharHeight(term, tab.wrapper) || 16;
        const lines = Math.trunc(_touchAccumY / lineHeight);
        if (lines) {
          term.scrollLines(lines);
          _touchAccumY -= lines * lineHeight;
        }
      }
    }
  }, { passive: false, capture: true });

  term.element.addEventListener('touchend', e => {
    clearTimeout(_longPressTimer);
    if (_pinchStartDist > 0 && e.touches.length < 2) {
      _pinchStartDist = 0;
      if (term.options.fontSize) {
        settings.fontSize = term.options.fontSize;
        try { saveSettings(); } catch {}
      }
      return;
    }
    if (_isSelectingDrag) {
      _isSelectingDrag = false;
      _selAnchor = null;
      if (e.changedTouches.length) {
        showTermSelectionBar(e.changedTouches[0].clientX, e.changedTouches[0].clientY);
      }
      return;
    }
    if (termSelectMode) {
      _selAnchor = null;
      return;
    }
    if (_isDraggingTouch) {
      _tapPos = null;
      setTimeout(() => { _isDraggingTouch = false; }, 120);
      return;
    }
    if (!_tapPos || e.changedTouches.length !== 1) return;
    const touch = e.changedTouches[0];
    const dx = Math.abs(touch.clientX - _tapPos.x);
    const dy = Math.abs(touch.clientY - _tapPos.y);
    const dt = Date.now() - _tapPos.time;

    if (dx < 10 && dy < 10 && dt < 300) {
      // If selection bar is visible and user taps outside it, clear selection
      if (term.hasSelection()) {
        term.clearSelection();
        hideTermSelectionBar();
      }
      if (Date.now() - _keyboardDismissedAt < 400) {
        _tapPos = null;
        return;
      }
      // Short tap -> mouse click
      const evt = new MouseEvent('mousedown', { clientX: touch.clientX, clientY: touch.clientY, button: 0, bubbles: true });
      term.element.dispatchEvent(evt);
      const upEvt = new MouseEvent('mouseup', { clientX: touch.clientX, clientY: touch.clientY, button: 0, bubbles: true });
      term.element.dispatchEvent(upEvt);
    }
    _tapPos = null;
  }, { passive: true });

  // Suppress synthetic clicks following a swipe/scroll gesture or keyboard dismissal
  tab.wrapper.addEventListener('click', e => {
    if (_isDraggingTouch || (Date.now() - _keyboardDismissedAt < 400)) {
      e.stopPropagation();
      e.preventDefault();
    }
  }, true);

  // Fit terminal then connect WebSocket — ensures WS uses correct dimensions
  requestAnimationFrame(() => {
    fitTerm(tab);
    if (!tab.closed) connectWebSocket(tab, false);
  });

  // Pinch-to-zoom on mobile
  let lastPinchDist = 0;
  tab.wrapper.addEventListener('touchstart', e => {
    if (e.touches.length === 2) {
      lastPinchDist = Math.hypot(
        e.touches[0].clientX - e.touches[1].clientX,
        e.touches[0].clientY - e.touches[1].clientY
      );
    }
  }, { passive: true });
  tab.wrapper.addEventListener('touchmove', e => {
    if (e.touches.length === 2) {
      e.preventDefault();
      const dist = Math.hypot(
        e.touches[0].clientX - e.touches[1].clientX,
        e.touches[0].clientY - e.touches[1].clientY
      );
      const delta = dist - lastPinchDist;
      if (Math.abs(delta) > 10) {
        const curSize = tab.term.options.fontSize || 14;
        const newSize = Math.max(10, Math.min(28, curSize + (delta > 0 ? 1 : -1)));
        tab.term.options.fontSize = newSize;
        if (tab.fitAddon) tab.fitAddon.fit();
        // Deliberately NOT persisted: a pinch gesture is transient, and writing it into
        // wt-settings silently changed the user's saved default for every future tab.
        // Font size is set deliberately from Settings → Appearance.
        lastPinchDist = dist;
      }
    }
  }, { passive: false });
  tab.wrapper.addEventListener('touchend', e => {
    if (e.touches.length < 2) lastPinchDist = 0;
  }, { passive: true });
}

