let _keyboardDismissedAt = 0;

function triggerHaptic(type = 'light') {
  try {
    if (!('vibrate' in navigator)) return;
    if (type === 'light') navigator.vibrate(10);
    else if (type === 'medium') navigator.vibrate(25);
    else if (type === 'heavy') navigator.vibrate([30, 50, 30]);
  } catch {}
}

function sendKey(key) {
  triggerHaptic('light');
  let modified = key;
  if (key.length === 1) {
    if (ctrlLatch) {
      const code = key.toLowerCase().charCodeAt(0);
      if (code >= 97 && code <= 122) { // a-z -> 0x01..0x1a
        modified = String.fromCharCode(code - 96);
      } else if (key === '[') {
        modified = '\x1b';
      } else if (key === '\\') {
        modified = '\x1c';
      }
      ctrlLatch = false;
    }
    if (shiftLatch && modified >= 'a' && modified <= 'z') {
      modified = modified.toUpperCase();
    }
    shiftLatch = false;
    if (altLatch && modified.charCodeAt(0) >= 0x20) {
      modified = '\x1b' + modified;
      altLatch = false;
    }
    updateModifierButtons();
  } else {
    shiftLatch = false;
    altLatch = false;
    ctrlLatch = false;
    updateModifierButtons();
  }
  const tab = (typeof getTermCtxTarget === 'function' ? getTermCtxTarget() : null) || getActiveTab();
  if (!tab) return;
  if (tab.ws && tab.ws.readyState === WebSocket.OPEN) {
    sendTerminalInput(tab, modified);
  } else {
    try {
      const now = Date.now();
      if (!tab._discToastAt || now - tab._discToastAt > 5000) {
        tab._discToastAt = now;
        toast('Terminal reconnecting — key not sent', 'warning');
      }
    } catch {}
  }
  tab?.term?.focus();
}

function sendCtrlP() {
  sendKey('\x10');
  openFinder();
}

// UTF-8 safe base64 (OSC 52). atob/btoa are Latin-1 only and throw on
// emoji/CJK — those payloads silently lost the clipboard sync entirely.
// Sanitizes whitespace, line breaks (RFC 2045), and URL-safe chars.
function b64ToUtf8(b64) {
  let clean = (b64 || '').replace(/[\s\r\n]+/g, '').replace(/-/g, '+').replace(/_/g, '/');
  while (clean.length % 4) clean += '=';
  const bin = atob(clean);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new TextDecoder().decode(bytes);
}
function utf8ToB64(str) {
  const bytes = new TextEncoder().encode(str);
  let bin = '';
  const CHUNK = 0x8000; // chunked: avoid blowing the arg limit on big clips
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
  }
  return btoa(bin);
}

